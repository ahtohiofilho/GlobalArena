using System.Numerics;
using GlobalArena.Runtime;

namespace GlobalArena.Simulation;

public enum CanonicalPhysicalProductionChannel : byte
{
    AssignedWorker = 1,
    ExpeditionCamp = 2
}

public enum CanonicalPhysicalFinalUseChannel : byte
{
    ResidentLocal = 1,
    ExpeditionRations = 2
}

/// <summary>
/// Recorded inside an executed tick, not reconstructed from hypothetical VS82
/// supply. Camp-origin food belongs to an expedition ledger, not local stock.
/// </summary>
public readonly record struct CanonicalExecutedPhysicalProductionRow(
    ulong SourceFineTile, uint Commodity, CanonicalPhysicalProductionChannel Channel,
    EconomicActivityKind? Activity, ulong JourneyOrderId, ulong ProducedRaw);

/// <summary>
/// An actual physical final-use destination. The production vintage and source
/// of consumed inventory are NOT known; old stock may supply this use.
/// </summary>
public readonly record struct CanonicalExecutedPhysicalFinalUseRow(
    ulong DestinationFineTile, uint Commodity,
    CanonicalPhysicalFinalUseChannel Channel, ulong JourneyOrderId, ulong ConsumedRaw);

/// <summary>
/// A local stock identity: before + freshly produced at this tile - local
/// consumed = after. Expedition cargo is accounted for separately.
/// </summary>
public readonly record struct CanonicalExecutedPhysicalStockReconciliationRow(
    ulong FineTile, uint Commodity, ulong OpeningRaw,
    ulong WorkerProducedRaw, ulong ResidentConsumedRaw, ulong ClosingRaw);

/// <summary>
/// Non-persistent, replay-derived physical evidence from an ACTUALLY executed
/// canonical closing tick. The signed-by-hash tick is the authoritative event;
/// this sidecar is deterministically regenerated by canonical save replay.
/// Not a chain of provenance from a producer to a later consumer.
/// </summary>
public sealed class CanonicalExecutedPhysicalCycleProvenance
{
    private readonly CanonicalPhysicalTacticalSession _originSession;
    private readonly ulong _workerRevision;
    private readonly ulong _transportRevision;
    private readonly int _journalCount;
    private readonly string _closingHash;
    private readonly CanonicalExecutedPhysicalProductionRow[] _production;
    private readonly CanonicalExecutedPhysicalFinalUseRow[] _use;
    private readonly CanonicalExecutedPhysicalStockReconciliationRow[] _stock;

    public ulong CycleOrdinal { get; }
    public ulong ClosingMovementTurn { get; }
    public ulong ActuallyProducedRaw { get; }
    public ulong ActuallyConsumedRaw { get; }
    public ulong ActuallyUnmetFoodRaw { get; }
    public ulong TotalRealPopulation { get; }
    public string ClosingWorldHashHex => _closingHash;
    public IReadOnlyList<CanonicalExecutedPhysicalProductionRow> Production => Array.AsReadOnly(_production);
    public IReadOnlyList<CanonicalExecutedPhysicalFinalUseRow> FinalUse => Array.AsReadOnly(_use);
    public IReadOnlyList<CanonicalExecutedPhysicalStockReconciliationRow> LocalStock => Array.AsReadOnly(_stock);

    public bool ProvesActualProductionBySourceAndCommodity => true;
    public bool ProvesActualFinalUseAtDestination => true;
    public bool ProvesWhichProducerSuppliedAConsumedUnit => false;
    public bool AuthenticatesIntermediateInputsOrCrossCycleInventoryVintage => false;
    public bool CanAuthorizeRealPurchasingPower => false;
    public bool IsNewCanonicalSaveField => false;
    public bool IsReconstructedOnCanonicalSaveReplay => true;
    public bool CreatesProductionOrMoney => false;

    private CanonicalExecutedPhysicalCycleProvenance(
        CanonicalPhysicalTacticalSession session,
        PhysicalEconomicCycle closed,
        IReadOnlyList<PhysicalCommodityStock> opening,
        IReadOnlyList<PhysicalCommodityStock> ending,
        IReadOnlyList<CanonicalExecutedPhysicalProductionRow> produced,
        IReadOnlyList<CanonicalExecutedPhysicalFinalUseRow> used)
    {
        _originSession = session;
        var state = session.State;
        var journal = session.Events;
        if (state.Cycles.Count == 0 ||
            state.Cycles[^1] != closed ||
            state.MovementTurn != closed.MovementTurn ||
            journal.Count == 0 || journal[^1].Kind != "tick" ||
            journal[^1].AfterHashHex != session.CurrentHash.HexDigest)
            throw new InvalidOperationException(
                "A provenance receipt must be recorded on the actual completed closing tick.");

        CycleOrdinal = checked((ulong)state.Cycles.Count);
        ClosingMovementTurn = closed.MovementTurn;
        ActuallyProducedRaw = closed.ProducedRaw;
        ActuallyConsumedRaw = closed.FoodConsumedRaw;
        ActuallyUnmetFoodRaw = closed.FoodUnmetRaw;
        TotalRealPopulation = state.TotalWorkers;
        _closingHash = session.CurrentHash.HexDigest;
        _journalCount = journal.Count;
        _workerRevision = state.WorkerRevision;
        _transportRevision = session.TransportNetwork.Revision;

        _production = produced.OrderBy(r => r.SourceFineTile)
            .ThenBy(r => r.Commodity).ThenBy(r => r.Channel)
            .ThenBy(r => r.Activity).ThenBy(r => r.JourneyOrderId).ToArray();
        _use = used.OrderBy(r => r.DestinationFineTile)
            .ThenBy(r => r.Commodity).ThenBy(r => r.Channel)
            .ThenBy(r => r.JourneyOrderId).ToArray();

        if (_production.Any(x => x.SourceFineTile == 0 || x.Commodity == 0 ||
                x.ProducedRaw == 0 ||
                (x.Channel == CanonicalPhysicalProductionChannel.AssignedWorker
                    ? x.JourneyOrderId != 0 || x.Activity is null
                    : x.Channel != CanonicalPhysicalProductionChannel.ExpeditionCamp ||
                      x.JourneyOrderId == 0 || x.Activity is not null)) ||
            _use.Any(x => x.DestinationFineTile == 0 || x.Commodity != 1U ||
                x.ConsumedRaw == 0 ||
                (x.Channel == CanonicalPhysicalFinalUseChannel.ResidentLocal
                    ? x.JourneyOrderId != 0
                    : x.Channel != CanonicalPhysicalFinalUseChannel.ExpeditionRations ||
                      x.JourneyOrderId == 0)) ||
            _production.GroupBy(x => (
                x.SourceFineTile, x.Commodity, x.Channel, x.Activity, x.JourneyOrderId))
                .Any(g => g.Count() != 1) ||
            _use.GroupBy(x => (
                x.DestinationFineTile, x.Commodity, x.Channel, x.JourneyOrderId))
                .Any(g => g.Count() != 1))
            throw new InvalidOperationException(
                "Executed physical provenance has invalid or duplicate identities.");

        var gross = _production.Aggregate(BigInteger.Zero, (a, x) => a + x.ProducedRaw);
        var consumed = _use.Aggregate(BigInteger.Zero, (a, x) => a + x.ConsumedRaw);
        if (gross != new BigInteger(closed.ProducedRaw) ||
            consumed != new BigInteger(closed.FoodConsumedRaw))
            throw new InvalidOperationException(
                "Executed source/destination totals differ from the canonical cycle.");

        var before = opening.ToDictionary(x => (
            Tile: x.TileId.FineStrategicCellId.Value, Commodity: x.Commodity.Value),
            x => x.RawQuantity);
        var after = ending.ToDictionary(x => (
            Tile: x.TileId.FineStrategicCellId.Value, Commodity: x.Commodity.Value),
            x => x.RawQuantity);
        var localProduction = _production
            .Where(x => x.Channel == CanonicalPhysicalProductionChannel.AssignedWorker)
            .GroupBy(x => (Tile: x.SourceFineTile, x.Commodity))
            .ToDictionary(g => g.Key, g => g.Aggregate(
                BigInteger.Zero, (v, x) => v + x.ProducedRaw));
        var localConsumption = _use
            .Where(x => x.Channel == CanonicalPhysicalFinalUseChannel.ResidentLocal)
            .GroupBy(x => (Tile: x.DestinationFineTile, x.Commodity))
            .ToDictionary(g => g.Key, g => g.Aggregate(
                BigInteger.Zero, (v, x) => v + x.ConsumedRaw));
        var keys = before.Keys.Concat(after.Keys).Concat(localProduction.Keys)
            .Concat(localConsumption.Keys).Distinct().OrderBy(x => x.Tile)
            .ThenBy(x => x.Commodity).ToArray();

        _stock = keys.Select(key =>
        {
            var openingRaw = before.GetValueOrDefault(key);
            var closingRaw = after.GetValueOrDefault(key);
            var made = localProduction.GetValueOrDefault(key);
            var consumedAtSite = localConsumption.GetValueOrDefault(key);
            if ((BigInteger)openingRaw + made - consumedAtSite != closingRaw)
                throw new InvalidOperationException(
                    "Executed local commodity stocks fail physical conservation.");
            return new CanonicalExecutedPhysicalStockReconciliationRow(
                key.Tile, key.Commodity, openingRaw,
                checked((ulong)made), checked((ulong)consumedAtSite), closingRaw);
        }).ToArray();
    }

    internal static CanonicalExecutedPhysicalCycleProvenance FromExecutedClosingTick(
        CanonicalPhysicalTacticalSession session, PhysicalEconomicCycle closed,
        IReadOnlyList<PhysicalCommodityStock> opening,
        IReadOnlyList<PhysicalCommodityStock> ending,
        IReadOnlyList<CanonicalExecutedPhysicalProductionRow> produced,
        IReadOnlyList<CanonicalExecutedPhysicalFinalUseRow> used)
    {
        var receipt = new CanonicalExecutedPhysicalCycleProvenance(
            session, closed, opening, ending, produced, used);
        receipt.VerifyIndependent();
        return receipt;
    }

    public void RequireCurrent(CanonicalPhysicalTacticalSession session)
    {
        ArgumentNullException.ThrowIfNull(session);
        var state = session.State;
        var journal = session.Events;
        if (!ReferenceEquals(session, _originSession) ||
            state.Cycles.Count != checked((int)CycleOrdinal) ||
            state.Cycles[^1].MovementTurn != ClosingMovementTurn ||
            state.MovementTurn != ClosingMovementTurn ||
            state.WorkerRevision != _workerRevision ||
            session.TransportNetwork.Revision != _transportRevision ||
            journal.Count != _journalCount ||
            journal[^1].Kind != "tick" ||
            journal[^1].AfterHashHex != _closingHash ||
            session.CurrentHash.HexDigest != _closingHash)
            throw new InvalidOperationException(
                "Executed provenance belongs to a different or stale canonical state.");
    }

    public void VerifyIndependent()
    {
        RequireCurrent(_originSession);
        var cycle = _originSession.State.Cycles[^1];
        if (cycle.ProducedRaw != ActuallyProducedRaw ||
            cycle.FoodConsumedRaw != ActuallyConsumedRaw ||
            cycle.FoodUnmetRaw != ActuallyUnmetFoodRaw ||
            _originSession.State.TotalWorkers != TotalRealPopulation ||
            _production.Aggregate(BigInteger.Zero,
                (total, row) => total + row.ProducedRaw) != new BigInteger(ActuallyProducedRaw) ||
            _use.Aggregate(BigInteger.Zero,
                (total, row) => total + row.ConsumedRaw) != new BigInteger(ActuallyConsumedRaw))
            throw new InvalidOperationException(
                "Physical provenance no longer reconciles to real cycle totals.");
        var currentStocks = _originSession.State.Stocks.ToDictionary(
            x => (Tile: x.TileId.FineStrategicCellId.Value,
                  Commodity: x.Commodity.Value), x => x.RawQuantity);
        if (currentStocks.Count != _stock.Length || _stock.Any(x =>
            !currentStocks.TryGetValue((x.FineTile, x.Commodity), out var value) ||
            value != x.ClosingRaw ||
            (BigInteger)x.OpeningRaw + x.WorkerProducedRaw -
                x.ResidentConsumedRaw != x.ClosingRaw))
            throw new InvalidOperationException(
                "Physical provenance disagrees with the canonical closing inventory.");
        RequireCurrent(_originSession);
    }
}
