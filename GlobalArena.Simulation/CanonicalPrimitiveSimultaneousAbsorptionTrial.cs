using System.Numerics;
using GlobalArena.Runtime;

namespace GlobalArena.Simulation;

/// <summary>
/// Both planned local use and authenticated arrivals in ONE market/commodity.
/// Positive hypothetical absorption is NOT a settled sale or actual consumption.
/// Relative price functions are VS78 sensitivities, never cash or buying power.
/// </summary>
public sealed record CanonicalPrimitiveSimultaneousMarketRow(
    EconomicPointId Market,
    CommodityId Commodity,
    BigInteger ProposedLocalAbsorptionRaw,
    BigInteger ProposedRemoteAbsorptionRaw,
    BigInteger TotalHypotheticallyAbsorbedRaw,
    BigInteger BasalResidentDemandSignalRaw,
    CanonicalEndogenousPriceIndex GentleAveragePriceIndex,
    CanonicalEndogenousPriceIndex GentleLastMarginalPriceIndex,
    CanonicalEndogenousPriceIndex GentleGrossRevenueIndex,
    CanonicalEndogenousPriceIndex SteepAveragePriceIndex,
    CanonicalEndogenousPriceIndex SteepLastMarginalPriceIndex,
    CanonicalEndogenousPriceIndex SteepGrossRevenueIndex);

/// <summary>
/// All quantities below remain per commodity; independent paid-food V12
/// receipts are OBSERVATIONS, not generated by this experimental batch.
/// </summary>
public sealed record CanonicalPrimitiveSimultaneousCommodityRow(
    CommodityId Commodity,
    EconomicActivityKind Activity,
    BigInteger PotentialRaw,
    BigInteger ExperimentallyFeasibleRaw,
    BigInteger LocallyAbsorbedRaw,
    BigInteger RemotelyAbsorbedRaw,
    BigInteger NeverExtractedRaw,
    BigInteger ProjectedDemandSignalRaw,
    CanonicalEndogenousPriceIndex GentleGrossRevenueIndex,
    CanonicalEndogenousPriceIndex SteepGrossRevenueIndex,
    BigInteger? IndependentExecutedFoodPurchaseRaw,
    BigInteger? IndependentExecutedFoodPaymentMicrocredits);

internal sealed record CanonicalPrimitiveSimultaneousAbsorptionReconstruction(
    CanonicalPrimitiveSimultaneousMarketRow[] Markets,
    CanonicalPrimitiveSimultaneousCommodityRow[] Commodities);

/// <summary>
/// VS96: read-only whole-world macro absorption of a single VS95 trial.
/// Every unit proposed for local use or through a valid remote lot is
/// hypothetically absorbed at exactly one inhabited market; unrelated
/// potential stays UNEXTRACTED. Basal demand sets the relative price curve,
/// not the quantity absorbed, and no monetary or stock transaction occurs.
/// </summary>
public sealed class CanonicalPrimitiveSimultaneousAbsorptionTrial
{
    private readonly CanonicalPhysicalTacticalSession _session;
    private readonly CanonicalPrimitiveSiteDiscovery _sites;
    private readonly CanonicalPrimitivePhysicalDispositionTrial _disposition95;
    private readonly CanonicalPrimitiveSimultaneousMarketRow[] _markets;
    private readonly CanonicalPrimitiveSimultaneousCommodityRow[] _commodities;

    public IReadOnlyList<CanonicalPrimitiveSimultaneousMarketRow> Markets { get; }
    public IReadOnlyList<CanonicalPrimitiveSimultaneousCommodityRow> Commodities { get; }
    public ulong CompletedEconomicCycleMovementTurn =>
        _disposition95.CompletedEconomicCycleMovementTurn;
    public bool UsesAuthenticatedVs95LocalAndRemoteFlows => true;
    public bool HypotheticallyAbsorbsAllProposedPhysicalQuantity => true;
    public bool TreatsDemandSignalAsPhysicalConsumptionCap => false;
    public bool CreatesUnintentionalInventory => false;
    public bool InventsUnplannedExtraction => false;
    public bool ReportsNominalWoodOrStonePrices => false;
    public bool ConvertsRelativePriceToRealMicrocredits => false;
    public bool ClaimsHypotheticalAbsorptionAsExecutedSale => false;
    public bool ImplementsAbstractPurchasingPower => false;
    public bool MutatesCanonicalWorldOrSave => false;
    public bool CanAuthorizeSettlement => false;

    private CanonicalPrimitiveSimultaneousAbsorptionTrial(
        CanonicalPhysicalTacticalSession session,
        CanonicalPrimitiveSiteDiscovery sites,
        CanonicalPrimitivePhysicalDispositionTrial disposition95,
        CanonicalPrimitiveSimultaneousAbsorptionReconstruction result)
    {
        _session = session;
        _sites = sites;
        _disposition95 = disposition95;
        _markets = result.Markets;
        _commodities = result.Commodities;
        Markets = Array.AsReadOnly(_markets);
        Commodities = Array.AsReadOnly(_commodities);
    }

    internal void RequireSameSites(CanonicalPrimitiveSiteDiscovery sites)
    {
        if (!ReferenceEquals(_sites, sites))
            throw new InvalidOperationException(
                "VS97 must use the precise certified VS96 site discovery.");
        RequireCurrent(_session);
    }

    internal void RequireSameDisposition(
        CanonicalPrimitivePhysicalDispositionTrial disposition)
    {
        if (!ReferenceEquals(_disposition95, disposition))
            throw new InvalidOperationException(
                "Abstract revenue must reference the exact VS96-certified VS95 disposition.");
        RequireCurrent(_session);
    }

    public void RequireCurrent(CanonicalPhysicalTacticalSession session)
    {
        if (!ReferenceEquals(_session, session))
            throw new InvalidOperationException(
                "VS96 absorption belongs to a different physical game session.");
        _sites.RequireCurrent(session);
        _disposition95.RequireCurrent(session);
        _disposition95.RequireSameSites(_sites);
    }

    private static CanonicalPrimitiveSimultaneousAbsorptionReconstruction Reconstruct(
        CanonicalPhysicalTacticalSession session,
        CanonicalPrimitiveSiteDiscovery sites,
        CanonicalPrimitivePhysicalDispositionTrial disposition95)
    {
        sites.RequireCurrent(session);
        disposition95.RequireCurrent(session);
        disposition95.RequireSameSites(sites);
        disposition95.VerifyIndependent();

        var demandByMarket = sites.Flows.DemandFlows.ToDictionary(
            x => (Market: x.EconomicPointId, Commodity: x.CommodityId),
            x => x.RawQuantity);
        var allSources = disposition95.Sources.ToDictionary(
            x => (x.Source, x.Commodity, x.Activity));
        var commodityById = disposition95.Commodities.ToDictionary(
            x => x.Commodity);
        var map = sites.CommodityMapping;

        if (commodityById.Count != 3 ||
            !commodityById.TryGetValue(map.Food, out var food) ||
            food.Activity != EconomicActivityKind.Agriculture ||
            !commodityById.TryGetValue(map.Wood, out var wood) ||
            wood.Activity != EconomicActivityKind.Forestry ||
            !commodityById.TryGetValue(map.Stone, out var stone) ||
            stone.Activity != EconomicActivityKind.Mining ||
            allSources.Count != disposition95.Sources.Count ||
            disposition95.Sources.Count != checked(sites.Sites.Count * 3) ||
            demandByMarket.Count != checked(sites.Sites.Count * 3))
            throw new InvalidOperationException(
                "VS96 cannot join different primitive commodities or incomplete live sources.");

        var local = new Dictionary<(EconomicPointId Market, CommodityId Commodity),
            BigInteger>();
        var totalOut = new Dictionary<
            (EconomicPointId Source, CommodityId Commodity,
             EconomicActivityKind Activity), BigInteger>();
        foreach (var row in disposition95.Sources)
        {
            var source = sites.At(row.Source);
            if (source is null || source.ResidentWorkers == 0 ||
                !demandByMarket.ContainsKey((row.Source, row.Commodity)) ||
                !commodityById.TryGetValue(row.Commodity, out var matched) ||
                matched.Activity != row.Activity ||
                row.ProposedLocalUseRaw + row.ProposedRemoteDeliveryRaw +
                    row.TotalNotExtractedRaw != row.PotentialRaw ||
                row.ProposedLocalUseRaw + row.ProposedRemoteDeliveryRaw >
                    row.FeasibleRaw)
                throw new InvalidOperationException(
                    "A VS95 physical source cannot be observed outside its certified site, commodity or conservation envelope.");
            var key = (row.Source, row.Commodity);
            local.TryGetValue(key, out var previous);
            local[key] = previous + row.ProposedLocalUseRaw;
        }

        // Remote market deliveries are traced from each actual VS81-authorized
        // lot. VS95 already proved origin/source conservation and transport
        // entitlements; this independently checks both sides of every pair.
        var arrivals = new Dictionary<
            (EconomicPointId Market, CommodityId Commodity), BigInteger>();
        foreach (var lot in disposition95.ProposedRemoteLots)
        {
            var offer = lot.Offer;
            var key = (offer.Source, offer.Commodity, offer.Activity);
            var buyer = (offer.Buyer, offer.Commodity);
            if (lot.RawQuantity == 0UL || !allSources.ContainsKey(key) ||
                !demandByMarket.TryGetValue(buyer, out var signal) ||
                signal != offer.BuyerPriceDemandSignalRaw ||
                !commodityById.TryGetValue(offer.Commodity, out var commodity) ||
                commodity.Activity != offer.Activity)
                throw new InvalidOperationException(
                    "A remote arrival must be traced to one live VS95 institutionally checked origin and buyer.");
            totalOut.TryGetValue(key, out var dispatched);
            totalOut[key] = dispatched + lot.RawQuantity;
            arrivals.TryGetValue(buyer, out var delivered);
            arrivals[buyer] = delivered + lot.RawQuantity;
        }

        foreach (var row in disposition95.Sources)
        {
            totalOut.TryGetValue((row.Source, row.Commodity, row.Activity),
                out var sent);
            if (sent != row.ProposedRemoteDeliveryRaw)
                throw new InvalidOperationException(
                    "VS96 cannot drop or duplicate dispatched lots.");
        }
        var auditedBuyers = disposition95.Buyers.ToDictionary(
            x => (x.Buyer, x.Commodity));
        if (auditedBuyers.Count != disposition95.Buyers.Count ||
            auditedBuyers.Count != arrivals.Count)
            throw new InvalidOperationException(
                "VS96 must reconcile every VS95 receiving market exactly once.");
        foreach (var (key, quantity) in arrivals)
            if (!auditedBuyers.TryGetValue(key, out var declared) ||
                declared.ProposedRemoteArrivalRaw != quantity ||
                declared.ProjectedDemandPressureRaw != demandByMarket[key])
                throw new InvalidOperationException(
                    "VS96 arrived quantities disagree with the signed VS95 physical buyer ledger.");

        // Include inactive-but-inhabited product markets with zero offers.
        // Demand remains a SIGNAL, and quantities above demand are accepted.
        var rows = new List<CanonicalPrimitiveSimultaneousMarketRow>();
        foreach (var d in demandByMarket.OrderBy(x => x.Key.Market.Value)
            .ThenBy(x => x.Key.Commodity.Value))
        {
            local.TryGetValue(d.Key, out var near);
            arrivals.TryGetValue(d.Key, out var remote);
            var quantity = near + remote;
            var pressure = new BigInteger(d.Value);
            var gentle = CanonicalEndogenousLocalPriceComparison.Calculate(
                quantity, pressure, 1);
            var steep = CanonicalEndogenousLocalPriceComparison.Calculate(
                quantity, pressure, 2);
            rows.Add(new(d.Key.Market, d.Key.Commodity,
                near, remote, quantity, pressure,
                gentle.Average, gentle.Last, gentle.Revenue,
                steep.Average, steep.Last, steep.Revenue));
        }

        var totals = new List<CanonicalPrimitiveSimultaneousCommodityRow>();
        foreach (var c in disposition95.Commodities)
        {
            var inMarkets = rows.Where(x => x.Commodity == c.Commodity).ToArray();
            var localRaw = inMarkets.Aggregate(BigInteger.Zero,
                (sum, x) => sum + x.ProposedLocalAbsorptionRaw);
            var remoteRaw = inMarkets.Aggregate(BigInteger.Zero,
                (sum, x) => sum + x.ProposedRemoteAbsorptionRaw);
            var demand = inMarkets.Aggregate(BigInteger.Zero,
                (sum, x) => sum + x.BasalResidentDemandSignalRaw);
            var gentleRevenue = inMarkets.Aggregate(
                CanonicalEndogenousPriceIndex.Zero,
                (sum, x) => CanonicalEndogenousPriceIndex.Add(
                    sum, x.GentleGrossRevenueIndex));
            var steepRevenue = inMarkets.Aggregate(
                CanonicalEndogenousPriceIndex.Zero,
                (sum, x) => CanonicalEndogenousPriceIndex.Add(
                    sum, x.SteepGrossRevenueIndex));
            if (localRaw != c.ProposedLocalUseRaw ||
                remoteRaw != c.ProposedRemoteDeliveryRaw ||
                demand != c.ProjectedDemandPressureRaw ||
                localRaw + remoteRaw + c.TotalNotExtractedRaw !=
                    c.TotalPotentialRaw)
                throw new InvalidOperationException(
                    "Market absorption must conserve every commodity across all local and remote markets.");
            totals.Add(new(c.Commodity, c.Activity,
                c.TotalPotentialRaw, c.TotalFeasibleRaw,
                localRaw, remoteRaw, c.TotalNotExtractedRaw,
                demand, gentleRevenue, steepRevenue,
                c.IndependentlyExecutedLocalFoodPurchaseRaw,
                c.IndependentlyExecutedFoodPaymentMicrocredits));
        }

        // Freight preflight is proof of route rights/cost only: it MUST NOT
        // be repeated here or silently converted into an actual payment.
        if ((disposition95.ProposedRemoteLots.Count > 0) !=
            (disposition95.InstitutionalFreightPreflight is not null))
            throw new InvalidOperationException(
                "Executed-looking freight must not be inferred from an unaudited proposal.");
        sites.RequireCurrent(session);
        disposition95.RequireCurrent(session);
        return new(rows.ToArray(),
            totals.OrderBy(x => x.Commodity.Value).ToArray());
    }

    public void VerifyIndependent()
    {
        RequireCurrent(_session);
        var reconstructed = Reconstruct(_session, _sites, _disposition95);
        if (!_markets.SequenceEqual(reconstructed.Markets) ||
            !_commodities.SequenceEqual(reconstructed.Commodities))
            throw new InvalidOperationException(
                "VS96 independent simultaneous local/remote absorption replay disagrees with the certified physical disposition.");
        RequireCurrent(_session);
    }

    public static CanonicalPrimitiveSimultaneousAbsorptionTrial FromCertifiedDisposition(
        CanonicalPhysicalTacticalSession session,
        CanonicalPrimitiveSiteDiscovery currentSites,
        CanonicalPrimitivePhysicalDispositionTrial disposition95)
    {
        ArgumentNullException.ThrowIfNull(session);
        ArgumentNullException.ThrowIfNull(currentSites);
        ArgumentNullException.ThrowIfNull(disposition95);
        var result = Reconstruct(session, currentSites, disposition95);
        var trial = new CanonicalPrimitiveSimultaneousAbsorptionTrial(
            session, currentSites, disposition95, result);
        trial.VerifyIndependent();
        return trial;
    }
}
